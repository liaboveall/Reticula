use crate::ast::MAX_FUNCTION_ARGS;

/// Static metadata for a built-in spreadsheet function.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FunctionMeta {
    /// Canonical uppercase function name.
    pub name: &'static str,
    /// Minimum accepted argument count.
    pub min_args: usize,
    /// Maximum accepted argument count (`MAX_FUNCTION_ARGS` for variadics).
    pub max_args: usize,
    /// Whether this function is volatile on edit or host environment change.
    pub is_volatile: bool,
    /// Parameter signature list shown in formula-bar signature help.
    pub params: &'static [&'static str],
    /// Concise English summary shown in formula-bar completion popovers.
    pub summary: &'static str,
}

const fn f(
    name: &'static str,
    min_args: usize,
    max_args: usize,
    is_volatile: bool,
    params: &'static [&'static str],
    summary: &'static str,
) -> FunctionMeta {
    FunctionMeta {
        name,
        min_args,
        max_args,
        is_volatile,
        params,
        summary,
    }
}

