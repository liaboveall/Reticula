//! Metadata catalog for all 69 built-in Layer-0 and Layer-1 functions
//! (`13-m1a.md` 5.5, `14-m1b.md` 5.3 & 6.1).
//!
//! Shared between formula evaluation, `FormulaEngine` volatile registration,
//! and `lang_service` completions / arity diagnostics / signature help.

use crate::ast::MAX_FUNCTION_ARGS;

/// Static metadata for a built-in spreadsheet function.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FunctionMeta {
    /// Canonical uppercase function name.
    pub name: &'static str,
    /// Minimum accepted argument count.
    pub min_args: usize,
    /// Maximum accepted argument count (`MAX_FUNCTION_ARGS` for variadics).
    pub max_args: usize,
    /// Whether this function reads [`super::EvalEnv`] (`TODAY`, `NOW`, `RAND`, `RANDBETWEEN`).
    pub is_volatile: bool,
    /// Parameter signature list shown in formula-bar signature help.
    pub params: &'static [&'static str],
    /// Concise English summary shown in formula-bar completion popovers.
    pub summary: &'static str,
}

const fn f(
    name: &'static str,
    min_args: usize,
    max_args: usize,
    is_volatile: bool,
    params: &'static [&'static str],
    summary: &'static str,
) -> FunctionMeta {
    FunctionMeta {
        name,
        min_args,
        max_args,
        is_volatile,
        params,
        summary,
    }
}

