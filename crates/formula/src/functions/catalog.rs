/// Binary-searches [`FUNCTION_CATALOG`] case-insensitively.
#[must_use]
pub fn lookup_function_meta(name: &str) -> Option<&'static FunctionMeta> {
    if name.bytes().all(|b| b.is_ascii_uppercase()) {
        FUNCTION_CATALOG
            .binary_search_by(|m| m.name.cmp(name))
            .ok()
            .and_then(|idx| FUNCTION_CATALOG.get(idx))
    } else {
        let upper = name.to_ascii_uppercase();
        FUNCTION_CATALOG
            .binary_search_by(|m| m.name.cmp(upper.as_str()))
            .ok()
            .and_then(|idx| FUNCTION_CATALOG.get(idx))
    }
}

/// Whether `name` (already uppercase in bound ASTs) is a volatile function.
#[must_use]
pub fn is_volatile_function(name: &str) -> bool {
    matches!(
        name,
        "TODAY" | "NOW" | "RAND" | "RANDBETWEEN" | "RANDARRAY" | "INDIRECT" | "OFFSET"
    )
}

/// Whether `name` (already uppercase in bound ASTs) responds to local hidden/filtered rows.
#[must_use]
pub fn is_filter_sensitive_function(name: &str) -> bool {
    matches!(name, "SUBTOTAL" | "AGGREGATE")
}

#[cfg(test)]
#[allow(clippy::indexing_slicing, clippy::unwrap_used)]
mod tests {
    use alloc::collections::BTreeSet;

    use super::{
        FUNCTION_CATALOG, is_filter_sensitive_function, is_volatile_function, lookup_function_meta,
    };

    #[test]
    fn catalog_has_200_strictly_sorted_unique_entries() {
        assert_eq!(FUNCTION_CATALOG.len(), 200);
        let mut seen = BTreeSet::new();
        for pair in FUNCTION_CATALOG.windows(2) {
            assert!(
                pair[0].name < pair[1].name,
                "catalog not strictly sorted: {} >= {}",
                pair[0].name,
                pair[1].name
            );
        }
        for meta in FUNCTION_CATALOG {
            assert!(seen.insert(meta.name), "duplicate name: {}", meta.name);
            assert!(meta.min_args <= meta.max_args, "bad arity: {}", meta.name);
            assert!(!meta.summary.is_empty(), "empty summary: {}", meta.name);
            assert_eq!(lookup_function_meta(meta.name).copied(), Some(meta));
            assert_eq!(meta.is_volatile, is_volatile_function(meta.name));
        }
        assert!(is_filter_sensitive_function("SUBTOTAL"));
        assert!(is_filter_sensitive_function("AGGREGATE"));
        assert!(!is_filter_sensitive_function("SUM"));
    }
}
