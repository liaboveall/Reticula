//! TypeScript files generated from the Rust sources and checked in.
//!
//! A viewport page is bytes, so unlike the structured messages it has no type
//! that could be exported. What the grid needs instead is the layout the
//! encoder writes, and proof that it reads that layout the same way:
//!
//! - the layout constants, straight from the encoder's own;
//! - a page encoded by the engine together with what it holds, which the
//!   grid's unit tests decode and compare.
//!
//! Both are checked in so that the front end can be type-checked and tested
//! without building anything. `--check` fails when either is out of date.

use std::fmt::Write as _;

use reticula_core::format::NumberFormat;
use reticula_core::sheet::Sheet;
use reticula_core::value::Value;
use reticula_core::viewport::{self, Page};

use crate::util::{self, Result};

const LAYOUT_PATH: &str = "packages/protocol/src/generated/viewport-layout.ts";
const FIXTURE_PATH: &str = "packages/protocol/src/generated/viewport-fixture.ts";

const BANNER: &str = "// Generated by `cargo xtask codegen`. Do not edit.\n";

pub fn run(check: bool) -> Result {
    util::step(if check {
        "generated files are up to date"
    } else {
        "generated files"
    });
    for (path, content) in [(LAYOUT_PATH, layout()), (FIXTURE_PATH, fixture())] {
        let file = util::root().join(path);
        let current = std::fs::read_to_string(&file).unwrap_or_default();
        if current == content {
            println!("{path}: up to date");
        } else if check {
            return Err(format!("{path} is out of date; run `cargo xtask codegen`"));
        } else {
            if let Some(directory) = file.parent() {
                std::fs::create_dir_all(directory)
                    .map_err(|error| format!("cannot create {}: {error}", directory.display()))?;
            }
            std::fs::write(&file, content)
                .map_err(|error| format!("cannot write {}: {error}", file.display()))?;
            println!("{path}: written");
        }
    }
    Ok(())
}

/// The constants of the page layout. The documentation of each is with its
/// definition in the encoder.
fn layout() -> String {
    macro_rules! constants {
        ($($name:ident),+ $(,)?) => {
            [$((stringify!($name), viewport::$name as u64)),+]
        };
    }
    let constants = constants![
        VERSION,
        PAGE_ROWS,
        PAGE_COLS,
        HEADER_LEN,
        VERSION_AT,
        SHEET_AT,
        FIRST_ROW_AT,
        FIRST_COL_AT,
        ROW_COUNT_AT,
        COL_COUNT_AT,
        TEXT_LEN_AT,
        EPOCH_AT,
        ID_LEN,
        CELL_LEN,
        CELL_TEXT_START_AT,
        CELL_TEXT_LEN_AT,
        CELL_STYLE_AT,
        CELL_FLAGS_AT,
        FLAG_NUMBER,
        MAX_SUBSCRIBED_PAGE_ROWS,
        MAX_SUBSCRIBED_PAGE_COLS,
    ];

    let mut out = String::from(BANNER);
    out.push_str(
        "//\n// The layout of a viewport page, as the engine writes it. Each constant is\n\
         // documented where it is defined: crates/core/src/viewport.rs.\n\n",
    );
    for (name, value) in constants {
        let _ = writeln!(out, "export const {name} = {value};");
    }
    out
}

/// A page with every kind of content the layout has to carry, away from the
/// origin and cut short by the edge of its sheet on both sides.
fn fixture() -> String {
    const EPOCH: u32 = 7;
    const ROWS_ABOVE: u32 = viewport::PAGE_ROWS;
    const COLS_LEFT: usize = viewport::PAGE_COLS as usize;

    let mut formats = vec![NumberFormat::General; COLS_LEFT];
    formats.extend([NumberFormat::Fixed2, NumberFormat::Date]);
    let mut sheet = Sheet::new(&formats);
    for _ in 0..ROWS_ABOVE {
        sheet.push_row(&[]);
    }
    // Text of one, two and three bytes per character, and of four, which takes
    // two UTF-16 code units; numbers in two formats; empty cells and empty text.
    let rows: [[Cell; 2]; 6] = [
        [Cell::Text("品名 😀"), Cell::Number(45_351.0)],
        [Cell::Number(12.5), Cell::Text("")],
        [Cell::Number(-1234.005), Cell::Number(60.0)],
        [Cell::Empty, Cell::Text("混合 mixed 文本")],
        [Cell::Text("𝒳-ray café"), Cell::Number(46_342.75)],
        [Cell::Number(1.0e21), Cell::Empty],
    ];
    for row in rows {
        let mut values = vec![Value::Empty; COLS_LEFT];
        for cell in row {
            values.push(match cell {
                Cell::Empty => Value::Empty,
                Cell::Number(number) => Value::Number(number),
                Cell::Text(text) => sheet.add_string(text).map_or(Value::Empty, Value::Text),
            });
        }
        sheet.push_row(&values);
    }

    let page = Page { row: 1, col: 1 };
    let bytes = viewport::encode_page(&sheet, page, EPOCH, &mut String::new());
    let first_row = page.row * viewport::PAGE_ROWS;
    let first_col = page.col * viewport::PAGE_COLS;

    let mut out = String::from(BANNER);
    out.push_str(
        "//\n// A viewport page encoded by the engine, and what it holds. Decoding `hex`\n\
         // must give exactly the rest.\n\n",
    );
    out.push_str("export const fixture = {\n  hex: \"");
    for byte in &bytes {
        let _ = write!(out, "{byte:02x}");
    }
    out.push_str("\",\n");
    let _ = writeln!(out, "  epoch: {EPOCH},");
    let _ = writeln!(out, "  firstRow: {first_row},");
    let _ = writeln!(out, "  firstCol: {first_col},");
    let ids = |ids: Vec<u64>| -> String {
        let ids: Vec<String> = ids.iter().map(|id| format!("{id}n")).collect();
        ids.join(", ")
    };
    let _ = writeln!(
        out,
        "  rowIds: [{}],",
        ids((first_row..sheet.rows())
            .map(|row| sheet.row_id(row))
            .collect())
    );
    let _ = writeln!(
        out,
        "  colIds: [{}],",
        ids((first_col..sheet.cols())
            .map(|col| sheet.col_id(col))
            .collect())
    );
    out.push_str("  cells: [\n");
    for row in first_row..sheet.rows() {
        out.push_str("    [");
        for col in first_col..sheet.cols() {
            let mut text = String::new();
            let value = sheet.write_text(row, col, &mut text);
            let number = matches!(value, Value::Number(_));
            if col > first_col {
                out.push_str(", ");
            }
            let _ = write!(out, "{{ text: {}, number: {number} }}", quoted(&text));
        }
        out.push_str("],\n");
    }
    out.push_str("  ],\n} as const;\n");
    out
}

enum Cell {
    Empty,
    Number(f64),
    Text(&'static str),
}

/// A string as a double-quoted TypeScript literal.
fn quoted(text: &str) -> String {
    let mut out = String::from('"');
    for character in text.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            control if control.is_control() => {
                let _ = write!(out, "\\u{{{:x}}}", u32::from(control));
            }
            other => out.push(other),
        }
    }
    out.push('"');
    out
}
